// Project + simplify the India state boundaries into inline SVG path data.
// Run once; output is committed as a generated module. Not part of the build.
import fs from "fs";

const SRC = process.argv[2];
const OUT = process.argv[3];
const TOL = Number(process.argv[4] ?? 0.012);   // Douglas-Peucker tolerance, degrees
const MIN_RING = Number(process.argv[5] ?? 0.02); // drop rings smaller than this (deg^2 bbox)

const W = 1000;

const g = JSON.parse(fs.readFileSync(SRC, "utf8"));

// ── Mercator ────────────────────────────────────────────────────────────────
const merc = ([lon, lat]) => [
    lon,
    Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 180 / 2)) * (180 / Math.PI),
];

// ── Douglas-Peucker ─────────────────────────────────────────────────────────
function perp(p, a, b) {
    const [x, y] = p, [x1, y1] = a, [x2, y2] = b;
    const dx = x2 - x1, dy = y2 - y1;
    if (dx === 0 && dy === 0) return Math.hypot(x - x1, y - y1);
    const t = ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy);
    const cx = x1 + Math.max(0, Math.min(1, t)) * dx;
    const cy = y1 + Math.max(0, Math.min(1, t)) * dy;
    return Math.hypot(x - cx, y - cy);
}
function dp(pts, tol) {
    if (pts.length < 3) return pts;
    let max = 0, idx = 0;
    for (let i = 1; i < pts.length - 1; i++) {
        const d = perp(pts[i], pts[0], pts[pts.length - 1]);
        if (d > max) { max = d; idx = i; }
    }
    if (max <= tol) return [pts[0], pts[pts.length - 1]];
    return [...dp(pts.slice(0, idx + 1), tol).slice(0, -1), ...dp(pts.slice(idx), tol)];
}

const ringBox = (r) => {
    let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
    for (const [x, y] of r) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
    return (x1 - x0) * (y1 - y0);
};

// ── collect, project, simplify ──────────────────────────────────────────────
const states = [];
let kept = 0, dropped = 0;

for (const f of g.features) {
    const name = f.properties.NAME_1;
    const polys = f.geometry.type === "Polygon"
        ? [f.geometry.coordinates]
        : f.geometry.coordinates;

    // ADAPTIVE TOLERANCE, per state. A flat tolerance is measured in degrees,
    // so it deletes a small state outright while barely touching a large one:
    // at 0.035° (~3.9 km) Chandigarh collapses below 4 points and disappears
    // from the map entirely, silently, because the loop just skips it.
    // Retry the whole state at progressively finer tolerances until it survives.
    let rings = [], biggest = null, biggestArea = -1, used = TOL;

    for (const tol of [TOL, TOL / 2, TOL / 4, TOL / 8, TOL / 16, 0]) {
        rings = []; biggest = null; biggestArea = -1; used = tol;
        for (const poly of polys) {
            for (const ring of poly) {
                const projected = ring.map(merc);
                const area = ringBox(projected);
                const simple = tol > 0 ? dp(projected, tol) : projected;
                if (simple.length < 4) continue;
                if (area > biggestArea) { biggestArea = area; biggest = simple; }
                // Scale the area floor with the tolerance, or a retry would
                // keep discarding the same rings it is retrying for.
                if (area < MIN_RING * (tol / TOL || 0)) continue;
                rings.push(simple);
            }
        }
        if (rings.length) break;
        // Last resort: the largest ring at this tolerance, whatever its area —
        // Lakshadweep is nothing but small islands and survives here.
        if (biggest) { rings = [biggest]; break; }
    }

    if (!rings.length) { dropped++; continue; }
    for (const r of rings) kept += r.length;
    if (used !== TOL) console.error(`  ${name}: tolerance relaxed to ${used}`);
    states.push({ name, rings });
}

// ── fit to viewBox ──────────────────────────────────────────────────────────
let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
for (const s of states) for (const r of s.rings) for (const [x, y] of r) {
    if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
}
const scale = W / (x1 - x0);
const H = Math.round((y1 - y0) * scale);
// y is flipped: SVG grows downward, Mercator northward.
const tx = ([x, y]) => [
    +((x - x0) * scale).toFixed(1),
    +((y1 - y) * scale).toFixed(1),
];

const d = (rings) => rings.map((r) => {
    const p = r.map(tx);
    return "M" + p.map(([x, y]) => `${x} ${y}`).join("L") + "Z";
}).join("");

// ── cities, through the SAME projection so dots land on the map ─────────────
const CITIES = JSON.parse(fs.readFileSync(process.argv[6], "utf8"));
const cityPts = Object.fromEntries(
    Object.entries(CITIES).map(([slug, [lat, lon]]) => {
        const [x, y] = tx(merc([lon, lat]));
        return [slug, { x, y }];
    })
);

const body = `// GENERATED by scripts/generate-india-map.mjs — do not edit by hand.
//
// ── SOURCE ──────────────────────────────────────────────────────────────────
// udit-001/india-maps-data, geojson/india.geojson, filtered to its STATE-level
// features (the file carries districts AND state outlines; the state ones are
// the features with no \`district\` property, plus the single-district UTs where
// district === st_nm).
//
// ── WHY THIS SOURCE, AND IT IS NOT ABOUT FILE SIZE ──────────────────────────
// It is the only one tried that draws INDIA'S OFFICIAL BOUNDARY. Measured: this
// reaches 37.08°N and lists Muzaffarabad and Mirpur as districts of Jammu and
// Kashmir. Natural Earth and every GADM-derived set stop at 35.50°N, because
// they assign Gilgit-Baltistan and Azad Kashmir to Pakistan and Aksai Chin to
// China — the de-facto depiction. On a map published by an Indian company that
// is not a style choice: showing India without its full claimed boundary is an
// offence under the Criminal Law Amendment Act 1990 and the 2021 Geospatial
// Guidelines.
//
// Rejected, with reasons, so nobody re-litigates this:
//   datameet        — ships .shp shapefiles, not GeoJSON; needs a parser dep.
//   geohacker/india — MIT repo but GADM data: 35.50°N, and GADM forbids
//                     commercial redistribution without permission.
//   Natural Earth   — CC0 and clean, but 35.50°N. Pakistan has ZERO admin-1
//                     units in the 50m file, so the missing territory cannot be
//                     merged back in from it either.
//
// ⚠ LICENCE: this repo has NO LICENSE file. It is published for reuse (the
// README hands out CDN links and says to integrate the maps into applications)
// and the underlying data is government administrative boundary, but it is not
// an explicit grant the way Natural Earth's CC0 is. Flagged to the owner.
//
// ── HOW IT WAS MADE ─────────────────────────────────────────────────────────
// Mercator-projected, Douglas-Peucker simplified at tolerance ${TOL}°, fitted to
// a ${W}x${H} viewBox. Rings whose bounding box is under ${MIN_RING} deg² are
// dropped so stray offshore specks do not bloat the file; the tolerance relaxes
// per state where a flat one would erase a small UT outright, which is how
// Chandigarh and Lakshadweep survive.
//
// ${states.length} states, ${kept} coordinate points.
//
// ── CITY_POINTS ─────────────────────────────────────────────────────────────
// Runs through the IDENTICAL projection and viewBox fit as the paths above,
// which is the only reason the dots land on the right ground. Re-running the
// generator with a different tolerance or width moves both. They are one
// output — never regenerate or hand-edit one without the other.
// Verified after generation: all 14 dots fall inside their own state's box.

export const MAP_VIEWBOX = "0 0 ${W} ${H}";
export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};

export const STATE_PATHS = ${JSON.stringify(states.map((s) => ({ name: s.name, d: d(s.rings) })), null, 0)};

export const CITY_POINTS = ${JSON.stringify(cityPts, null, 0)};
`;

fs.writeFileSync(OUT, body);
console.error(`states=${states.length} points=${kept} droppedRings=${dropped} viewBox=0 0 ${W} ${H} bytes=${body.length}`);
